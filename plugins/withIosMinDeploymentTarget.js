const { withPodfile } = require("expo/config-plugins");

const MARKER = "# @generated by withIosMinDeploymentTarget";

/**
 * react_native_post_install() only normalizes IPHONEOS_DEPLOYMENT_TARGET on
 * each pod's main native target (installer.target_installation_results),
 * not on the separate "resource bundle" targets CocoaPods generates for
 * pods with resource_bundles (e.g. RNCAsyncStorage-RNCAsyncStorage_resources,
 * which ships pinned to 13.4). Xcode's supported deployment target floor
 * keeps rising, so a stale resource-bundle target fails the build even
 * though the app target itself is fine. This walks every target in the
 * Pods project and bumps any deployment target below the minimum.
 */
module.exports = function withIosMinDeploymentTarget(config, { minVersion = "15.1" } = {}) {
  return withPodfile(config, (config) => {
    const contents = config.modResults.contents;
    if (contents.includes(MARKER)) {
      return config;
    }

    const marker = "react_native_post_install(";
    const start = contents.indexOf(marker);
    if (start === -1) {
      throw new Error(
        "withIosMinDeploymentTarget: could not find react_native_post_install( call in Podfile"
      );
    }

    let depth = 0;
    let i = start + marker.length - 1;
    for (; i < contents.length; i++) {
      if (contents[i] === "(") depth++;
      else if (contents[i] === ")") {
        depth--;
        if (depth === 0) break;
      }
    }
    const insertAt = contents.indexOf("\n", i) + 1;

    const snippet = `
    ${MARKER}
    installer.pods_project.targets.each do |target|
      target.build_configurations.each do |build_config|
        current = build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET']
        if current && current.to_f < ${minVersion}
          build_config.build_settings['IPHONEOS_DEPLOYMENT_TARGET'] = '${minVersion}'
        end
      end
    end
`;

    config.modResults.contents =
      contents.slice(0, insertAt) + snippet + contents.slice(insertAt);
    return config;
  });
};
